def html_ref(r: dict) -> str:
    t = H.escape(r["titre"], quote=False)
    return (f'{H.escape(r["auteurs"], quote=False)} ({r["annee"]}). {t}. '
            f'<em>{H.escape(r["revue"], quote=False)}</em>.')
